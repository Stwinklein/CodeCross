from __future__ import annotations

"""A tiny A2A-compatible reviewer service for CodeCross.

Run it with:
    python -m uvicorn a2aproject.server:app --host 127.0.0.1 --port 9100

The service exposes an Agent Card and a JSON-RPC `message/send` endpoint. It can
either run deterministically for local debugging or call a real model when the
request includes `llm.api_key`.
"""

from typing import Any

from fastapi import FastAPI

from codecross.config import ModelSettings
from codecross.llm import ModelCallError, call_model_json, json_schema_instruction
from codecross.schemas import Finding, LineRange, ReviewerResult, TestIntent, new_id


app = FastAPI(title="CodeCross Demo A2A Reviewer")


def _extract_data_payload(request: dict[str, Any]) -> dict[str, Any]:
    """Read the first data part from an A2A-style `message/send` request."""

    message = (request.get("params") or {}).get("message") or {}
    for part in message.get("parts") or []:
        data = part.get("data")
        if isinstance(data, dict):
            return data
    raise ValueError("message/send did not contain a data part")


def _deterministic_review(payload: dict[str, Any]) -> ReviewerResult:
    """Local deterministic reviewer used when no model key is supplied."""

    reviewer = payload.get("reviewer") or {}
    reviewer_name = reviewer.get("name") or "a2a_reviewer"
    provider = reviewer.get("provider") or "a2a"
    model = reviewer.get("model") or "deterministic"
    diff = payload.get("diff") or ""
    target_file = "unknown.py"
    for line in diff.splitlines():
        if line.startswith("+++ b/"):
            target_file = line.removeprefix("+++ b/")
            break

    findings = []
    intents = []
    if "safe_divide" in diff or "divide" in diff:
        finding_id = new_id("finding")
        intent_id = new_id("intent")
        findings.append(
            Finding(
                finding_id=finding_id,
                source_reviewer=reviewer_name,
                model=f"a2a/{provider}/{model}",
                category="runtime",
                severity="high",
                confidence="high",
                file_path=target_file,
                line_range=LineRange(start=1, end=4),
                problem="A2A reviewer found a divide path without zero-denominator handling.",
                evidence="The diff includes a divide-like function that directly evaluates a / b.",
                impact="Callers may receive ZeroDivisionError instead of a controlled result.",
                suggestion="Define and implement a zero-denominator contract.",
                reproduction_hint="Call the function with denominator 0.",
                related_test_intent_ids=[intent_id],
            )
        )
        intents.append(
            TestIntent(
                test_intent_id=intent_id,
                source_reviewer=reviewer_name,
                target_file=target_file,
                target_symbol="safe_divide" if "safe_divide" in diff else "divide",
                scenario="zero denominator",
                reason="A2A reviewer identified a boundary path.",
                expected_behavior="The function should handle denominator 0 without raising.",
                risk_category="runtime",
                priority="high",
                related_finding_ids=[finding_id],
            )
        )

    return ReviewerResult(
        reviewer_name=reviewer_name,
        model=f"a2a/{provider}/{model}",
        findings=findings,
        test_intents=intents,
        reviewer_notes="Generated by the demo A2A reviewer service.",
    )


def build_reviewer_result(payload: dict[str, Any]) -> ReviewerResult:
    """Build ReviewerResult from A2A payload.

    If an API key is present, the remote reviewer owns the LLM call. This is the
    coupling reduction you wanted: CodeCross no longer needs to know how that
    reviewer is implemented, only that it returns ReviewerResult JSON.
    """

    llm = payload.get("llm") or {}
    if not llm.get("api_key"):
        return _deterministic_review(payload)

    reviewer = payload.get("reviewer") or {}
    settings = ModelSettings(
        role="a2a_reviewer",
        name=reviewer.get("name") or "a2a_reviewer",
        provider=llm.get("provider") or reviewer.get("provider") or "openai",
        model=llm.get("model") or reviewer.get("model") or "",
        api_key_override=llm.get("api_key"),
        base_url_override=llm.get("base_url"),
        temperature=0.2,
    )
    result = call_model_json(
        settings,
        [
            (
                "system",
                "You are a remote A2A code reviewer. Return ReviewerResult JSON only.",
            ),
            (
                "user",
                "Review this CodeCross payload and return findings/test intents.\n"
                f"Payload:\n{payload}\n\n"
                f"{json_schema_instruction(ReviewerResult)}",
            ),
        ],
        ReviewerResult,
    )
    return result  # type: ignore[return-value]


@app.get("/.well-known/agent-card.json")
@app.get("/.well-known/agent-card")
def agent_card() -> dict[str, Any]:
    """Expose minimal discovery metadata for A2A clients."""

    return {
        "name": "CodeCross Demo A2A Reviewer",
        "description": "Demo reviewer that returns CodeCross ReviewerResult artifacts.",
        "url": "http://127.0.0.1:9100/a2a",
        "capabilities": {"streaming": False},
        "skills": [
            {
                "id": "code_review",
                "name": "Code review",
                "description": "Review a unified diff and return structured findings.",
            }
        ],
    }


@app.post("/a2a")
def a2a_rpc(request: dict[str, Any]) -> dict[str, Any]:
    """Handle minimal A2A JSON-RPC `message/send` calls."""

    request_id = request.get("id")
    if request.get("method") != "message/send":
        return {
            "jsonrpc": "2.0",
            "id": request_id,
            "error": {"code": -32601, "message": "Only message/send is supported."},
        }

    try:
        result = build_reviewer_result(_extract_data_payload(request))
        return {
            "jsonrpc": "2.0",
            "id": request_id,
            "result": {
                "status": {"state": "completed"},
                "artifacts": [
                    {
                        "name": "reviewer_result",
                        "parts": [{"kind": "data", "data": result.model_dump(mode="json")}],
                    }
                ],
            },
        }
    except (ValueError, ModelCallError) as exc:
        return {
            "jsonrpc": "2.0",
            "id": request_id,
            "error": {"code": -32000, "message": f"{type(exc).__name__}: {exc}"},
        }
